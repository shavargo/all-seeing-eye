func charshift(reg byte) byte {
	if reg < 26 {
		return reg + 'A'
	}
	if reg < 52 {
		return reg + 'G'
	}
	if reg < 62 {
		return reg - 4
	}
	if reg == 62 {
		return '+'
	}
	if reg == 63 {
		return '/'
	}
	return 0
}

// GenerateValidate computes the expected GameSpy validation response string
// based on the cipher secret, challenge string, and encryption type (0, 1, 2).
func GenerateValidate(cipher, secure string, enctype int) string {
	cipherBytes := []byte(cipher)
	secureBytes := []byte(secure)
	cipherLen := len(cipherBytes)
	secureLen := len(secureBytes)

	if cipherLen == 0 || secureLen == 0 {
		return ""
	}

	// 1. Initialize S-Box
	var enc [256]byte
	for j := 0; j < 256; j++ {
		enc[j] = byte(j)
	}

	// 2. Cipher shuffle
	var a, x byte
	for j := 0; j < 256; j++ {
		a += enc[j] + cipherBytes[j%cipherLen]
		x = enc[a]
		enc[a] = enc[j]
		enc[j] = x
	}

	// 3. Secure shuffle
	var tmp [66]byte
	var i, y, b byte
	a = 0
	for i = 0; int(i) < cipherLen && int(i) < len(secureBytes); i++ {
		a += secureBytes[i] + 1
		x = enc[a]
		b += x
		y = enc[b]
		enc[b] = x
		enc[a] = y
		tmp[i] = secureBytes[i] ^ enc[(x+y)&0xff]
	}

	totalLen := int(i)
	for totalLen%3 != 0 {
		tmp[totalLen] = 0
		totalLen++
	}

	// 4. Enctype 1 or 2 transformation
	if enctype == 1 {
		for k := 0; k < totalLen; k++ {
			tmp[k] = enctype1Data[tmp[k]]
		}
	} else if enctype == 2 {
		for k := 0; k < totalLen; k++ {
			tmp[k] = tmp[k] ^ cipherBytes[k%cipherLen]
		}
	}

	// 5. Base64-like charshift packing
	var out []byte
	for k := 0; k < totalLen; k += 3 {
		xVal := tmp[k]
		yVal := tmp[k+1]
		zVal := tmp[k+2]

		out = append(out, charshift(xVal>>2))
		out = append(out, charshift(((xVal&3)<<4)|(yVal>>4)))
		out = append(out, charshift(((yVal&15)<<2)|(zVal>>6)))
		out = append(out, charshift(zVal&63))
	}

	return string(out)
}
